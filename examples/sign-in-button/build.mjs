// Builds revoked-sign-in.js, the one file services copy, from
// src/revoked-sign-in.js and qrcode.mjs. Run after editing either:
//
//   node build.mjs
//
// The result has no imports or exports and runs in its own scope, so it
// loads as <script type="module"> and as a plain <script> alike.

import { readFile, writeFile } from 'node:fs/promises';

const here = new URL('.', import.meta.url);
const read = (path) => readFile(new URL(path, here), 'utf8');

function strip(text, file, replacements) {
  let out = text;
  for (const [pattern, replacement] of replacements) {
    if (!pattern.test(out)) throw new Error(`${file}: expected ${pattern} to match`);
    out = out.replace(pattern, replacement);
  }
  const left = out.match(/^\s*(import|export)\b.*$/m);
  if (left) throw new Error(`${file}: unexpected module syntax left: ${left[0].trim()}`);
  return out.trim();
}

const qr = strip(await read('qrcode.mjs'), 'qrcode.mjs', [
  [/^export const qrcode = /m, 'const qrcode = '],
  [/^export default qrcode;\s*$/m, ''],
  [/^export const stringToBytes = .*$/m, ''],
]);

const element = strip(await read('src/revoked-sign-in.js'), 'src/revoked-sign-in.js', [
  [/^import qrcode from '\.\.\/qrcode\.mjs';\s*$/m, ''],
]);

const out = `// "Continue with Revoked": the button and the panel it opens, in one file.
// Copy it next to your static files; nothing is fetched from anywhere else.
//
//   <script type="module" src="/revoked/revoked-sign-in.js"></script>
//   <revoked-sign-in start="/auth/revoked/start" wait="/auth/revoked/wait"></revoked-sign-in>
//
// Generated by build.mjs from src/revoked-sign-in.js and qrcode.mjs; edit
// those, not this file. README.md lists the attributes.
//
// Includes qrcode-generator by Kazuhiko Arase, under the MIT license (below).

(() => {
'use strict';

${qr}

${element}
})();
`;

await writeFile(new URL('revoked-sign-in.js', here), out);
console.log(`revoked-sign-in.js: ${(Buffer.byteLength(out) / 1024).toFixed(1)} KiB`);
